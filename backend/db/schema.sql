  id integer PRIMARY KEY CHECK (id = 1),
  company_name_ja text NOT NULL,
  company_name_en text NOT NULL,
  postal_code text NOT NULL DEFAULT '',
  address text NOT NULL DEFAULT '',
  tel_fax text NOT NULL DEFAULT '',
  mobile text NOT NULL DEFAULT '',
  email text NOT NULL DEFAULT '',
  registration_no text NOT NULL DEFAULT '',
  bank_branch text NOT NULL DEFAULT '',
  account_type_number text NOT NULL DEFAULT '',
  account_name text NOT NULL DEFAULT '',
  transfer_note text NOT NULL DEFAULT '',
  document_title text NOT NULL DEFAULT '請求書',
  document_subtitle text NOT NULL DEFAULT 'INVOICE',
  intro_sentence text NOT NULL DEFAULT '',
  currency text NOT NULL DEFAULT 'JPY',
  currency_symbol text NOT NULL DEFAULT '¥',
  invoice_prefix text NOT NULL DEFAULT 'ABI',
  separator text NOT NULL DEFAULT '-',
  year_format text NOT NULL DEFAULT 'YYYY',
  sequence_digits integer NOT NULL DEFAULT 4,
  restart_each_year boolean NOT NULL DEFAULT true,
  next_sequence integer NOT NULL DEFAULT 1,
  sequence_year integer NOT NULL DEFAULT 2026,
  last_invoice_no text NOT NULL DEFAULT '',
  next_payment_no integer NOT NULL DEFAULT 1,
  next_customer_no integer NOT NULL DEFAULT 1,
  next_draft_no integer NOT NULL DEFAULT 1,
  default_due_days integer NOT NULL DEFAULT 30,
  default_terms text NOT NULL DEFAULT '',
  default_tax_mode text NOT NULL DEFAULT 'Not applied',
  tax_rate numeric(6, 4) NOT NULL DEFAULT 0.10,
  tax_label text NOT NULL DEFAULT '消費税',
  tax_rounding text NOT NULL DEFAULT 'Round down',
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS payment_methods (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE,
  sort_order integer NOT NULL
);

CREATE TABLE IF NOT EXISTS units (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE,
  sort_order integer NOT NULL
);

CREATE TABLE IF NOT EXISTS customers (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_code text NOT NULL UNIQUE,
  name text NOT NULL,
  company_name text NOT NULL DEFAULT '',
  postal_code text NOT NULL DEFAULT '',
  address text NOT NULL DEFAULT '',
  phone text NOT NULL DEFAULT '',
  email text NOT NULL DEFAULT '',
  tax_reg_no text NOT NULL DEFAULT '',
  remarks text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS drafts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  draft_code text NOT NULL UNIQUE,
  status text NOT NULL DEFAULT 'Open',
  invoice_date date,
  due_date date,
  customer_id integer REFERENCES customers (id),
  subject text NOT NULL DEFAULT '',
  terms text NOT NULL DEFAULT '',
  remarks text NOT NULL DEFAULT '',
  discount_rate numeric(8, 6) NOT NULL DEFAULT 0,
  discount_fixed bigint NOT NULL DEFAULT 0,
  tax_mode text NOT NULL,
  tax_rate numeric(6, 4) NOT NULL,
  tax_rounding text NOT NULL,
  other_charges_label text NOT NULL DEFAULT '',
  other_charges bigint NOT NULL DEFAULT 0,
  replaces_invoice_id integer,
  estimated_total bigint NOT NULL DEFAULT 0,
  finalized_invoice_id integer,
  saved_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT drafts_status_chk CHECK (status IN ('Open', 'Finalized', 'Discarded'))
);

CREATE TABLE IF NOT EXISTS invoices (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  serial_no integer NOT NULL UNIQUE,
  invoice_no text NOT NULL UNIQUE,
  invoice_date date NOT NULL,
  due_date date,
  customer_id integer REFERENCES customers (id),
  customer_name text NOT NULL,
  customer_phone text NOT NULL DEFAULT '',
  company_name text NOT NULL DEFAULT '',
  postal_code text NOT NULL DEFAULT '',
  address text NOT NULL DEFAULT '',
  email text NOT NULL DEFAULT '',
  customer_reg_no text NOT NULL DEFAULT '',
  subject text NOT NULL DEFAULT '',
  terms text NOT NULL DEFAULT '',
  remarks text NOT NULL DEFAULT '',
  subtotal bigint NOT NULL,
  discount bigint NOT NULL,
  tax bigint NOT NULL,
  other_charges bigint NOT NULL,
  grand_total bigint NOT NULL,
  discount_rate numeric(8, 6) NOT NULL DEFAULT 0,
  discount_fixed bigint NOT NULL DEFAULT 0,
  tax_mode text NOT NULL,
  tax_rate numeric(6, 4) NOT NULL,
  tax_rounding text NOT NULL,
  tax_label text NOT NULL,
  other_charges_label text NOT NULL DEFAULT '',
  line_count integer NOT NULL,
  record_status text NOT NULL DEFAULT 'Issued',
  replaces_invoice_id integer REFERENCES invoices (id),
  replaced_by_invoice_id integer REFERENCES invoices (id),
  finalized_at timestamptz NOT NULL DEFAULT now(),
  cancelled_at timestamptz,
  cancel_reason text NOT NULL DEFAULT '',
  source_draft_id integer REFERENCES drafts (id),
  CONSTRAINT invoices_status_chk CHECK (record_status IN ('Issued', 'Cancelled'))
);

ALTER TABLE drafts
  DROP CONSTRAINT IF EXISTS drafts_replaces_invoice_id_fkey;
ALTER TABLE drafts
  ADD CONSTRAINT drafts_replaces_invoice_id_fkey
  FOREIGN KEY (replaces_invoice_id) REFERENCES invoices (id);

ALTER TABLE drafts
  DROP CONSTRAINT IF EXISTS drafts_finalized_invoice_id_fkey;
ALTER TABLE drafts
  ADD CONSTRAINT drafts_finalized_invoice_id_fkey
  FOREIGN KEY (finalized_invoice_id) REFERENCES invoices (id);

CREATE TABLE IF NOT EXISTS draft_lines (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  draft_id integer NOT NULL REFERENCES drafts (id) ON DELETE CASCADE,
  line_no integer NOT NULL,
  description text NOT NULL,
  qty numeric(12, 3) NOT NULL,
  unit text NOT NULL DEFAULT '',
  unit_price bigint NOT NULL,
  line_total bigint NOT NULL,
  UNIQUE (draft_id, line_no)
);

CREATE TABLE IF NOT EXISTS invoice_lines (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_id integer NOT NULL REFERENCES invoices (id) ON DELETE CASCADE,
  line_no integer NOT NULL,
  description text NOT NULL,
  qty numeric(12, 3) NOT NULL,
  unit text NOT NULL DEFAULT '',
  unit_price bigint NOT NULL,
  line_total bigint NOT NULL,
  UNIQUE (invoice_id, line_no)
);

CREATE TABLE IF NOT EXISTS payments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_code text NOT NULL UNIQUE,
  invoice_id integer NOT NULL REFERENCES invoices (id),
  customer_name text NOT NULL DEFAULT '',
  payment_date date NOT NULL,
  amount bigint NOT NULL,
  method text NOT NULL,
  reference text NOT NULL DEFAULT '',
  remarks text NOT NULL DEFAULT '',
  entry_type text NOT NULL,
  reverses_payment_id integer REFERENCES payments (id),
  status text NOT NULL,
  flag text NOT NULL DEFAULT '',
  recorded_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT payments_entry_chk CHECK (entry_type IN ('Payment', 'Reversal', 'Transfer')),
  CONSTRAINT payments_status_chk CHECK (status IN ('Active', 'Reversed'))
);

CREATE INDEX IF NOT EXISTS payments_invoice_idx ON payments (invoice_id);
CREATE INDEX IF NOT EXISTS invoices_date_idx ON invoices (invoice_date);
CREATE INDEX IF NOT EXISTS invoices_customer_idx ON invoices (customer_id);

CREATE TABLE IF NOT EXISTS audit_log (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  occurred_at timestamptz NOT NULL DEFAULT now(),
  operator_name text NOT NULL,
  action text NOT NULL,
  document text NOT NULL DEFAULT '',
  details text NOT NULL DEFAULT ''
);

CREATE INDEX IF NOT EXISTS audit_log_time_idx ON audit_log (occurred_at DESC);
